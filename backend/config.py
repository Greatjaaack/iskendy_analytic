"""Конфигурация приложения — один типизированный класс на pydantic BaseSettings.

Значения берутся из переменных окружения (в Docker — из env_file `.env`), имена полей
соответствуют именам переменных без учёта регистра: `iiko_web_url` ← `IIKO_WEB_URL`.
Так все параметры окружения собраны в одном месте, валидируются и имеют дефолты.
"""

from datetime import date

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    # Какая касса стоит за данными: `iiko` или `saby` (Saby Presto). Переключает
    # адаптер в `backend/pos/` — весь остальной код от кассы не зависит. В день
    # переезда меняется только эта переменная (и ключи ниже).
    pos_provider: str = "iiko"

    # iikoweb (внутренний API через cookie-сессию)
    iiko_web_url: str = "https://iskendi.iikoweb.ru"
    iiko_web_login: str = ""
    iiko_web_password: str = ""
    iiko_store_id: int = 161059

    # Saby (СБИС) Presto — публичный REST API, сервисная авторизация приложения.
    # Ключи создаются в кабинете: Настройки → Безопасность → Подключения к Saby.
    # Только чтение: в кассу мы не пишем никогда.
    saby_api_url: str = "https://api.sbis.ru"
    saby_auth_url: str = "https://online.sbis.ru/oauth/service/"
    saby_app_client_id: str = ""
    saby_app_secret: str = ""
    saby_secret_key: str = ""
    saby_point_id: int = 0  # идентификатор точки продаж (GET /retail/point/list)
    # TTL токена Saby не документирован — держим не дольше этого и обновляем по 401.
    saby_token_ttl_seconds: int = 3600
    # Как долго кэшируем каталог номенклатуры (он же даёт категорию блюда), сек.
    saby_menu_ttl_seconds: int = 3600

    # хранилище
    database_url: str = "sqlite:///./iskendi.db"
    # Сколько SQLite ждёт освобождения блокировки, прежде чем вернуть ошибку (мс).
    # Синк заменяет данные по дням большими транзакциями, и короткое ожидание лучше,
    # чем «database is locked» на запросе дашборда или ручки табло.
    sqlite_busy_timeout_ms: int = 5000
    files_dir: str = "/data/files"
    # Максимальный размер загружаемого файла (накладные/прайсы), МБ. У контейнера лимит
    # памяти 512 МБ, поэтому загрузка читается кусками и обрывается на этом пороге.
    max_upload_mb: int = 10

    # часовой пояс ресторана: определяет границы «сегодня/неделя/месяц» и расписание
    # синков. Не зависит от TZ контейнера (там обычно UTC). Точка московская (см. погоду).
    timezone: str = "Europe/Moscow"

    # TTL in-memory кэша живых чтений из iikoweb (get-data/OLAP), сек. 0 — кэш выключен.
    # Короткий TTL схлопывает повторные одинаковые запросы дашборда, не задерживая
    # обновление дольше этого окна. Сбрасывается при ручном синке.
    cache_ttl_seconds: int = 60

    # Интервал частого «прогрева» текущего дня в БД, сек (job `sync_today`). Дашборд
    # отдаёт «сегодня» из БД (быстро), а этот синк держит его свежим — компромисс между
    # свежестью и нагрузкой на iikoweb. 0 — выключить частый синк (останется часовой).
    today_sync_seconds: int = 180

    # Как часто ручка табло (`/api/orders/today`) ходит в живой iiko, ПОКА за сегодня
    # нет ни одного заказа, сек. Точка закрыта — спрашивать 6 раз в минуту незачем: за
    # ночь это ~4700 запросов ради пустого ответа. Как появится первый заказ, ручка
    # переходит на общий `cache_ttl_seconds`. Цена — первый заказ смены доедет до табло
    # с задержкой до этого значения. 0 — выключить «тихий» режим.
    idle_poll_seconds: int = 60

    # Сколько секунд ручка табло МАКСИМУМ ждёт живую кассу, прежде чем отдать
    # заказы из БД. Табло ждёт ответа 30 секунд и обрывает связь; ручка же при
    # больной кассе тратила 60 секунд на попытку, секунду на паузу и ещё 60 на
    # повтор — до 121 секунды. 27.08.2026 из-за этого табло не получило НИ ОДНОГО
    # ответа за два часа: даже удачные ответы приходили на 77–106-й секунде, то
    # есть заведомо позже, чем табло готово ждать. Терпеливое ожидание в пути,
    # по которому кто-то ждёт вживую, бесполезно: ответ, опоздавший к сроку
    # вызывающего, равен отсутствию ответа, только дороже.
    orders_live_budget_sec: int = 20

    # А вот фоновому синку торопиться некуда: его никто не ждёт, и его задача —
    # чтобы в БД лежали свежие заказы, из которых ручка табло ответит мгновенно.
    # Поэтому здесь терпение НАМЕРЕННО больше, чем у ручки: медленная касса
    # доедет в БД за минуту-другую, и табло этого даже не заметит.
    sync_poll_attempts: int = 120

    # Авторизация дашборда: один общий логин/пароль из .env (внутренний инструмент).
    # Пустой `auth_password` отключает вход (логин невозможен) — задать обязательно.
    auth_username: str = "admin"
    auth_password: str = ""
    # Секрет подписи JWT. Если пуст — выводится из пароля (`iskendy:<auth_password>`),
    # чтобы работало без доп. настройки; для ротации сессий задать свой.
    jwt_secret: str = ""
    # Срок жизни токена сессии, часов.
    jwt_ttl_hours: int = 12

    # Разрешённые источники для CORS, через запятую. На проде фронт и API живут за одним
    # адресом (nginx проксирует /api), поэтому CORS там не участвует вовсе; список нужен
    # для локальной разработки, где vite поднимается на 5173. Пусто = CORS выключен.
    cors_origins: str = "http://localhost:5173,http://127.0.0.1:5173"

    # Сервисный токен для внутренних read-only ручек (напр. табло заказов
    # iskendy_site тянет `/api/orders/today`). Пустой — ручка отключена (401).
    internal_token: str = ""

    # Сколько дней держать журнал синхронизаций (`sync_log`). Каждый синк пишет строку, а
    # `sync_today` идёт раз в 3 минуты — это ~950 строк в день: за три месяца таблица
    # выросла до 86 196 строк и стала крупнее самих продаж. 0 — не чистить.
    sync_log_keep_days: int = 30

    # Начало истории для бэкафилла заказов в БД (ISO `YYYY-MM-DD`). Если не задано —
    # определяется автоматически (probe по выручке: первая дата с продажами).
    history_start_date: date | None = None

    # День, с которого данные берёт ТЕКУЩАЯ касса (`POS_SWITCH_DATE`, ISO). Дни раньше
    # него синк не трогает — они уже в БД, а новая касса о них не знает. Без этого
    # первый синк после переезда на Saby затёр бы историю iiko пустотой, и восстановить
    # её было бы неоткуда: Saby отдаёт только свои продажи. Заполняется в день переезда.
    pos_switch_date: date | None = None

    # Google-таблица финансовой модели P&L (помесячные затраты/ставки). Импортируется
    # кнопкой «Обновить из таблицы» — бэкенд тянет публичный xlsx-экспорт (таблица
    # открыта «по ссылке»), парсит и заполняет `PnlMonth`. `pnl_sheet_id` — id документа.
    pnl_sheet_id: str = "1RltnlXXNkskwYLoZocUJils_4oydj2iNj0M1jK2b9SY"

    @property
    def cors_origin_list(self) -> list[str]:
        """Разобранный `cors_origins` → список адресов (пустой = CORS не подключаем)."""
        return [o.strip() for o in self.cors_origins.split(",") if o.strip()]


settings = Settings()
