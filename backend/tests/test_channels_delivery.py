"""Галка «без доставки» в разрезе по каналам — по тому же правилу, что KPI.

Найдено на живых данных 26.09.2026: за сентябрь KPI показывал 3 727 чеков, а виджет
«Чеки и выручка по типу обслуживания» — 3 726. Заказ 20.09 «Балык + Кола» кассир отметил
и «Доставкой», и «С собой»; KPI отсекает доставку по ТОВАРАМ (`utils.is_delivery`) и
заказ оставлял, а разрез отсекал по «Статусу» и выбрасывал заказ целиком.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from constants import OLAP_FIELD_OPEN_DATE  # noqa: E402
from services.channels import channel_revenue  # noqa: E402
from services.dish_cuts import build_check_distribution  # noqa: E402

DAY = "2026-09-20"

# (номер, категория, имя, сумма) — строки разреза по заказам за один день
ROWS = [
    # кассир отметил и «Доставку», и «С собой», а товаров доставки нет — это «с собой»
    ("151", "Дюрюмы", "Балык", 1180),
    ("151", "Напитки", "Кола", 380),
    ("151", "Статус", "Доставка", 0),
    ("151", "Статус", "С собой", 0),
    # обычный заказ в зале
    ("152", "Дюрюмы", "Балык", 1180),
    ("152", "Статус", "В зале", 0),
    # настоящая доставка по товару, хотя статус «С собой» — при выкл. галке исчезает
    ("153", "Доставка", "Дюрюм_д", 900),
    ("153", "Статус", "С собой", 0),
]


def rows() -> list[dict]:
    return [
        {"field0": {"value": f"{DAY}, {n}, {cat}, {name}"}, "field1": {"value": s}}
        for n, cat, name, s in ROWS
    ]


def counts(include_delivery: bool) -> dict[str, int]:
    res = build_check_distribution(rows(), include_delivery)
    return {r["type"]: r["count"] for r in res["data"]} | {"total": res["total"]}


def test_без_доставки_чеки_считаются_как_в_kpi():
    """KPI без доставки: 2 чека (заказ 153 с доставочной позицией вычтен)."""
    assert counts(include_delivery=False) == {
        "С собой": 1,
        "В зале": 1,
        "Доставка": 0,
        "total": 2,
    }


def test_с_доставкой_поведение_прежнее():
    """Галка включена — как раньше: чек относится по «Статусу» (сильнейшему), и только
    без «Статуса» — по товару. Поэтому 151 — «Доставка», а 153 со статусом «С собой» —
    «С собой» (задокументировано в ручке `check-distribution`)."""
    assert counts(include_delivery=True) == {
        "Доставка": 1,
        "В зале": 1,
        "С собой": 1,
        "total": 3,
    }


def test_выручка_по_каналам_без_доставки_сходится_с_kpi():
    day = channel_revenue(rows(), OLAP_FIELD_OPEN_DATE, include_delivery=False)[DAY]
    # доставочная позиция 153 уходит в канал «доставка», который роутер при выкл. галке
    # не показывает; остальное — ровно выручка без доставки (1180 + 380 + 1180)
    assert day["с собой"] == 1560
    assert day["в зале"] == 1180
    assert day["с собой"] + day["в зале"] == 2740


def test_выручка_по_каналам_с_доставкой_без_изменений():
    day = channel_revenue(rows(), OLAP_FIELD_OPEN_DATE)[DAY]
    assert day == {"в зале": 1180, "с собой": 0, "доставка": 2460}
